# PowerShell script to download dependencies

Write-Host "Downloading TouchpadTracker dependencies..." -ForegroundColor Cyan

$ErrorActionPreference = "Stop"

# Create directories if they don't exist
$externalDir = Join-Path $PSScriptRoot "external"
$imguiDir = Join-Path $externalDir "imgui"
$gladDir = Join-Path $externalDir "glad"

New-Item -ItemType Directory -Force -Path $imguiDir | Out-Null
New-Item -ItemType Directory -Force -Path (Join-Path $imguiDir "backends") | Out-Null
New-Item -ItemType Directory -Force -Path $gladDir | Out-Null

# ImGui version
$imguiVersion = "1.90.1"
$imguiBaseUrl = "https://raw.githubusercontent.com/ocornut/imgui/v$imguiVersion"

# ImGui core files
$imguiFiles = @(
    "imgui.h",
    "imgui.cpp",
    "imgui_internal.h",
    "imgui_demo.cpp",
    "imgui_draw.cpp",
    "imgui_tables.cpp",
    "imgui_widgets.cpp",
    "imconfig.h",
    "imstb_rectpack.h",
    "imstb_textedit.h",
    "imstb_truetype.h"
)

# ImGui backend files
$imguiBackendFiles = @(
    "imgui_impl_win32.h",
    "imgui_impl_win32.cpp",
    "imgui_impl_opengl3.h",
    "imgui_impl_opengl3.cpp",
    "imgui_impl_opengl3_loader.h"
)

Write-Host "Downloading ImGui v$imguiVersion..." -ForegroundColor Yellow

foreach ($file in $imguiFiles) {
    $url = "$imguiBaseUrl/$file"
    $dest = Join-Path $imguiDir $file
    Write-Host "  Downloading $file..."
    try {
        Invoke-WebRequest -Uri $url -OutFile $dest -UseBasicParsing
    } catch {
        Write-Host "    Failed to download $file - will need manual download" -ForegroundColor Red
    }
}

foreach ($file in $imguiBackendFiles) {
    $url = "$imguiBaseUrl/backends/$file"
    $dest = Join-Path $imguiDir "backends" $file
    Write-Host "  Downloading backends/$file..."
    try {
        Invoke-WebRequest -Uri $url -OutFile $dest -UseBasicParsing
    } catch {
        Write-Host "    Failed to download backends/$file - will need manual download" -ForegroundColor Red
    }
}

